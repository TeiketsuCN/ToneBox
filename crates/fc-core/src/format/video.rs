//! 视频容器组 —— 既是输入，也能当输出目标。
//!
//! 和音频格式不同，这里存的不是"一种编码"，而是**容器**：同一个 mkv 里
//! 视频流可以是 copy（直接封装）或 h264/hevc/vp9/av1，音频流可以是 copy
//! 或按容器规矩重编。所以能力矩阵（哪个容器收哪种编码）写在这个文件里，
//! GUI 只照着画按钮。
//!
//! 产品边界：
//! - 只处理**第一条**视频流和第一条音轨；多音轨/字幕不做（音乐用户不需要）。
//! - AVI 的文件名后缀保持 `.avi`，但编码组合受老播放器限制，选项只给 copy/h264。
//! - 不做 DRM，也不做"从视频里扒流媒体"。

